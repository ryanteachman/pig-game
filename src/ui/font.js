export const FONT_KEY = 'pixfont';
export const LINE_HEIGHT = 10;
export const GLYPH_H = 8;

export function charWidth(ch) {
  const g = G[ch] || G['?'];
  return g[0].length;
}

// Width in pixels of a string at scale 1 (1px gap between glyphs).
export function measure(text) {
  let w = 0;
  for (const ch of text) w += charWidth(ch) + 1;
  return Math.max(0, w - 1);
}

// Word-wrap into lines no wider than maxWidth. Respects explicit '\n'.
export function wrap(text, maxWidth) {
  const lines = [];
  for (const para of String(text).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (measure(test) <= maxWidth || !line) line = test;
      else { lines.push(line); line = word; }
    }
    lines.push(line);
  }
  return lines;
}

export function buildFont(scene) {
  if (scene.textures.exists(FONT_KEY)) return;
  const chars = Object.keys(G);
  const cellW = 6, cellH = GLYPH_H;
  const perRow = 16;
  const rows = Math.ceil(chars.length / perRow);
  const tex = scene.textures.createCanvas(FONT_KEY, perRow * cellW, rows * cellH);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  const data = { font: FONT_KEY, size: GLYPH_H, lineHeight: LINE_HEIGHT, chars: {} };
  const W = perRow * cellW, H = rows * cellH;
  chars.forEach((ch, i) => {
    const g = G[ch];
    const ox = (i % perRow) * cellW, oy = Math.floor(i / perRow) * cellH;
    g.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') ctx.fillRect(ox + x, oy + y, 1, 1);
    });
    const w = g[0].length;
    data.chars[ch.codePointAt(0)] = {
      x: ox, y: oy, width: w, height: cellH,
      centerX: Math.floor(w / 2), centerY: Math.floor(cellH / 2),
      xOffset: 0, yOffset: 0, xAdvance: w + 1,
      data: {}, kerning: {},
      u0: ox / W, v0: oy / H, u1: (ox + w) / W, v1: (oy + cellH) / H,
    };
  });
  tex.refresh();
  scene.cache.bitmapFont.add(FONT_KEY, { data, texture: FONT_KEY, frame: null });
}
